@pytest.mark.parametrize("text", [
    lambda b: rewritten(b).replace('name="' + UK_A_NAME + '"\n', ""),                     # no name=
    lambda b: "\n".join(ln for ln in rewritten(b).split("\n") if not ln.startswith("path=")),  # no path=
    lambda b: rewritten(b) + '\npath="C:/elsewhere"',                                      # two path=
    lambda b: rewritten(b) + '\nname="P00b EXP-01-UK-A again"',                            # two name=
    lambda b: 'x={\n' + rewritten(b) + '\n}',                                              # all keys nested
    lambda b: 'tags={\n' + rewritten(b),                                                   # unclosed block
    lambda b: rewritten(b) + "\n}",                                                        # unbalanced
    lambda b: 'name={ "' + UK_A_NAME + '" }\n' + rewritten(b).split("\n", 1)[1],           # name is a block
])
def test_ambiguous_or_broken_files_are_refused(uk, text):
    user, build = uk
    t = text(build)
    dest = put(user, t)
    with pytest.raises(KitError):
        inst.uninstall(UK_A, user, build_root=build)
    assert dest.read_text(encoding="utf-8") == t


def test_file_name_must_match_the_id(uk):
    user, build = uk
    other = user / "mod" / "p00b_EXP-01-UK-B.mod"
    other.write_text(rewritten(build), encoding="utf-8")
    assert not inst.is_kit_file(other, UK_A, user, build)
    assert not inst.is_kit_file(other, "EXP-01-UK-B", user, build)   # its name= / path= are UK-A's
    with pytest.raises(KitError):
        inst.uninstall("EXP-01-UK-B", user, build_root=build)
    assert other.exists()


def test_reinstall_over_launcher_rewritten_file(uk, tmp_path):
    user, build = uk
    dest = put(user, rewritten(build))
    before = snapshot(tmp_path)
    assert inst.install(UK_A, user, build_root=build) == dest
    after = snapshot(tmp_path)
    assert set(after) == set(before)
    assert [k for k in after if after[k] != before[k]] == ["user/mod/p00b_EXP-01-UK-A.mod"]
    text = dest.read_text(encoding="utf-8")
    assert text == (f'name="{UK_A_NAME}"\nversion="1"\nsupported_version="1.19.*"\ntags={{\n\t"Map"\n}}\n'
                    f'path="{(build / UK_A).resolve().as_posix()}"\n')
    assert inst.is_kit_file(dest, UK_A, user, build)
    assert inst.uninstall(UK_A, user, build_root=build) == dest


def test_rewritten_symlink_is_refused(uk, tmp_path):
    user, build = uk
    real = tmp_path / "elsewhere.mod"
    real.write_text(rewritten(build), encoding="utf-8")
    link = user / "mod" / f"p00b_{UK_A}.mod"
    try:
        os.symlink(real, link)
    except (OSError, NotImplementedError):
        pytest.skip("symlinks not available on this system")
