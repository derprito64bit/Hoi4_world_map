"""install.py writes only $HOI4_USER_DIR/mod/p00b_<ID>.mod and refuses every other destination."""
import os

import pytest

from experiments import install as inst
from experiments.common import KitError, is_within, safe_join


@pytest.fixture
def setup(tmp_path):
    user = tmp_path / "user"
    (user / "mod").mkdir(parents=True)
    (user / "dlc_load.json").write_text('{"enabled_mods": []}', encoding="utf-8")
    build = tmp_path / "build"
    (build / "EXP-01A").mkdir(parents=True)
    (build / "EXP-01A" / "descriptor.mod").write_text(
        'name="P00b EXP-01A test"\nversion="1"\nsupported_version="1.19.*"\ntags={\n\t"Map"\n}\n'
        'replace_path="history/states"\n# generated by p00b-experiment-kit\n', encoding="utf-8")
    return user, build


def snapshot(root):
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


def test_install_writes_one_file_inside_user_mod(setup, tmp_path):
    user, build = setup
    before = snapshot(tmp_path)
    dest = inst.install("EXP-01A", user, build_root=build)
    after = snapshot(tmp_path)
    assert dest == user / "mod" / "p00b_EXP-01A.mod"
    assert set(after) - set(before) == {"user/mod/p00b_EXP-01A.mod"}
    assert all(after[k] == before[k] for k in before)          # dlc_load.json etc. untouched
    text = dest.read_text(encoding="utf-8")
    assert f'path="{(build / "EXP-01A").resolve().as_posix()}"' in text
    assert 'replace_path="history/states"' in text and 'name="P00b EXP-01A test"' in text
    assert inst.MARKER in text


def test_uninstall_removes_only_own_file(setup):
    user, build = setup
    inst.install("EXP-01A", user, build_root=build)
    assert inst.uninstall("EXP-01A", user) == user / "mod" / "p00b_EXP-01A.mod"
    assert not (user / "mod" / "p00b_EXP-01A.mod").exists()
    assert inst.uninstall("EXP-01A", user) is None
    assert (user / "dlc_load.json").exists()


def test_refuses_foreign_files(setup):
    user, build = setup
    foreign = user / "mod" / "p00b_EXP-01A.mod"
    foreign.write_text('name="somebody else"\n', encoding="utf-8")
    with pytest.raises(KitError):
        inst.install("EXP-01A", user, build_root=build)
    with pytest.raises(KitError):
        inst.uninstall("EXP-01A", user)
    assert foreign.read_text(encoding="utf-8") == 'name="somebody else"\n'


@pytest.mark.parametrize("bad", ["../EXP-01A", "EXP-01A/../../x", "EXP-01A\\..\\x", "C:/x", "/etc/x", "dlc_load",
                                 "EXP-1A", "EXP-01A.mod/..", ""])
def test_rejects_bad_build_ids(setup, bad):
    user, build = setup
    with pytest.raises(KitError):
        inst.install(bad, user, build_root=build)


def test_refuses_missing_or_unset_user_dir(setup, tmp_path):
    _, build = setup
    with pytest.raises(KitError):
        inst.install("EXP-01A", None, build_root=build)
    with pytest.raises(KitError):
        inst.install("EXP-01A", tmp_path / "does-not-exist", build_root=build)


def test_refuses_unbuilt(setup):
    user, build = setup
    with pytest.raises(KitError):
        inst.install("EXP-02-300", user, build_root=build)


def test_refuses_mod_dir_symlink_escape(setup, tmp_path):
    user, build = setup
    outside = tmp_path / "elsewhere"
    outside.mkdir()
    (user / "mod").rmdir()
    try:
        os.symlink(outside, user / "mod", target_is_directory=True)
    except (OSError, NotImplementedError):
        try:                                   # Windows without symlink rights: a junction does the same
            import _winapi
            _winapi.CreateJunction(str(outside), str(user / "mod"))
        except (ImportError, OSError, AttributeError):
            pytest.skip("neither symlinks nor junctions available on this system")
    with pytest.raises(KitError):
        inst.install("EXP-01A", user, build_root=build)
    assert not any(outside.iterdir())


def test_dry_run_writes_nothing(setup, tmp_path):
    user, build = setup
    before = snapshot(tmp_path)
    inst.install("EXP-01A", user, build_root=build, dry_run=True)
    assert snapshot(tmp_path) == before


def test_safe_join_and_containment(tmp_path):
    assert is_within(tmp_path / "a" / "b", tmp_path)
    assert not is_within(tmp_path.parent, tmp_path)
    for bad in ("../x", "/abs", "C:/abs", "a/../../x"):
        with pytest.raises(KitError):
            safe_join(tmp_path, bad)
    assert safe_join(tmp_path, "a/b.txt") == tmp_path / "a" / "b.txt"
