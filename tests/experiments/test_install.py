def test_refuses_mod_dir_symlink_escape(setup, tmp_path):
    user, build = setup
    outside = tmp_path / "elsewhere"
    outside.mkdir()
    (user / "mod").rmdir()
    try:
        os.symlink(outside, user / "mod", target_is_directory=True)
    except (OSError, NotImplementedError):
        try:                                   # Windows without symlink rights: a junction does the same
            import _winapi
            _winapi.CreateJunction(str(outside), str(user / "mod"))
        except (ImportError, OSError, AttributeError):
            pytest.skip("neither symlinks nor junctions available on this system")
    with pytest.raises(KitError):
        inst.install("EXP-01A", user, build_root=build)
    assert not any(outside.iterdir())


def test_dry_run_writes_nothing(setup, tmp_path):
    user, build = setup
    before = snapshot(tmp_path)
    inst.install("EXP-01A", user, build_root=build, dry_run=True)
    assert snapshot(tmp_path) == before


def test_safe_join_and_containment(tmp_path):
    assert is_within(tmp_path / "a" / "b", tmp_path)
    assert not is_within(tmp_path.parent, tmp_path)
    for bad in ("../x", "/abs", "C:/abs", "a/../../x"):
        with pytest.raises(KitError):
            safe_join(tmp_path, bad)
    assert safe_join(tmp_path, "a/b.txt") == tmp_path / "a" / "b.txt"


# ---------------------------------------------------------------- launcher-rewritten .mod files (WU P00b-f1)
UK_A = "EXP-01-UK-A"
UK_A_NAME = "P00b EXP-01-UK-A sea-to-sea link between non-touching seas, UK control pair (type sea, sea Through)"
# exactly what the Paradox launcher left after install.py EXP-01-UK-A (owner report, 2026-09-28):
# '#' marker dropped, keys reordered, tab-indented tags, no final newline
REWRITTEN = ('name="' + UK_A_NAME + '"\nversion="1"\ntags={\n\t"Map"\n}\nsupported_version="1.19.*"\n'
             'path="C:/dev/Hoi4_world_map/build/experiments/EXP-01-UK-A"')
REAL_PATH = "C:/dev/Hoi4_world_map/build/experiments/EXP-01-UK-A"


@pytest.fixture
def uk(tmp_path):
    user = tmp_path / "user"
    (user / "mod").mkdir(parents=True)
    (user / "settings.txt").write_text("x", encoding="utf-8")
    build = tmp_path / "build" / "experiments"
    (build / UK_A).mkdir(parents=True)
    (build / UK_A / "descriptor.mod").write_text(
        f'name="{UK_A_NAME}"\nversion="1"\nsupported_version="1.19.*"\ntags={{\n\t"Map"\n}}\n'
        "# generated by p00b-experiment-kit (tools/experiments); do not edit\n", encoding="utf-8")
    return user, build


def rewritten(build, path=None, name=UK_A_NAME):
    """The launcher-rewritten text with its path= pointing at ``path`` (default: the fixture's build)."""
    path = (build / UK_A).resolve().as_posix() if path is None else path
    return REWRITTEN.replace(REAL_PATH, path).replace(UK_A_NAME, name)


def put(user, text, newline=""):
    dest = user / "mod" / f"p00b_{UK_A}.mod"
    with open(dest, "w", encoding="utf-8", newline=newline) as fh:
        fh.write(text)
    return dest


@pytest.mark.parametrize("newline", ["\n", "\r\n"])
def test_uninstall_deletes_launcher_rewritten_file(uk, newline):
    user, build = uk
    dest = put(user, rewritten(build), newline)
    assert inst.uninstall(UK_A, user, dry_run=True, build_root=build) == dest
    assert dest.exists()                                         # dry run keeps it
    assert inst.uninstall(UK_A, user, build_root=build) == dest
    assert not dest.exists()
    assert (user / "settings.txt").exists()


@pytest.mark.skipif(os.name != "nt", reason="the owner's file carries a Windows drive path")
def test_uninstall_deletes_the_owners_exact_bytes(uk):
    """The byte-exact file from the owner's machine, with the build root it points at."""
    user, _ = uk
    dest = put(user, REWRITTEN)
    real_root = Path(REAL_PATH).parent
    assert inst.is_kit_file(dest, UK_A, user, real_root)
    assert inst.uninstall(UK_A, user, build_root=real_root) == dest
    assert not dest.exists()


def test_uninstall_tolerates_bom_tabs_comments_and_any_order(uk):
    user, build = uk
    p = (build / UK_A).resolve().as_posix()
    text = ('\ufeff# a comment\n\tsupported_version = "1.19.*"\r\npath\t=\t"' + p + '"\ttags = { "Map" "Naval" }\n'
            'name = "' + UK_A_NAME + '"   version=1')
    dest = put(user, text)
    assert inst.uninstall(UK_A, user, build_root=build) == dest
    assert not dest.exists()


@pytest.mark.parametrize("path", [
    "C:/somewhere/else/build/experiments/EXP-01-UK-A",
    "/opt/other-repo/build/experiments/EXP-01-UK-A",
    "OTHER",                                     # relative: resolved against the user dir
    "BUILD/EXP-01-UK-B",                         # this repo, but another experiment
    "BUILD",                                     # this repo's build root itself
    "BUILD/EXP-01-UK-A/..",                      # escapes to the build root
    "BUILD/EXP-01-UK-A/sub",
])
def test_rewritten_file_with_foreign_path_is_refused(uk, path):
    user, build = uk
    (build / "EXP-01-UK-B").mkdir()
    path = path.replace("BUILD", build.resolve().as_posix())
    text = rewritten(build, path=path)
    dest = put(user, text)
    with pytest.raises(KitError, match="not written by this kit"):
        inst.uninstall(UK_A, user, build_root=build)
    with pytest.raises(KitError, match="not written by this kit"):
        inst.install(UK_A, user, build_root=build)
    assert dest.read_text(encoding="utf-8") == text                # untouched


