@pytest.fixture
def setup(tmp_path):
    user = tmp_path / "user"
    (user / "mod").mkdir(parents=True)
    (user / "dlc_load.json").write_text('{"enabled_mods": []}', encoding="utf-8")
    build = tmp_path / "build"
    (build / "EXP-01A").mkdir(parents=True)
    (build / "EXP-01A" / "descriptor.mod").write_text(
        'name="P00b EXP-01A test"\nversion="1"\nsupported_version="1.19.*"\ntags={\n\t"Map"\n}\n'
        'replace_path="history/states"\n# generated by p00b-experiment-kit\n', encoding="utf-8")
    return user, build


def snapshot(root):
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


def test_install_writes_one_file_inside_user_mod(setup, tmp_path):
    user, build = setup
    before = snapshot(tmp_path)
    dest = inst.install("EXP-01A", user, build_root=build)
    after = snapshot(tmp_path)
    assert dest == user / "mod" / "p00b_EXP-01A.mod"
    assert set(after) - set(before) == {"user/mod/p00b_EXP-01A.mod"}
    assert all(after[k] == before[k] for k in before)          # dlc_load.json etc. untouched
    text = dest.read_text(encoding="utf-8")
    assert f'path="{(build / "EXP-01A").resolve().as_posix()}"' in text
    assert 'replace_path="history/states"' in text and 'name="P00b EXP-01A test"' in text
    assert "#" not in text                                      # no marker comment: the launcher strips it anyway
    assert inst.is_kit_file(dest, "EXP-01A", user, build)


def test_uninstall_removes_only_own_file(setup):
    user, build = setup
    inst.install("EXP-01A", user, build_root=build)
    assert inst.uninstall("EXP-01A", user, build_root=build) == user / "mod" / "p00b_EXP-01A.mod"
    assert not (user / "mod" / "p00b_EXP-01A.mod").exists()
    assert inst.uninstall("EXP-01A", user, build_root=build) is None
    assert (user / "dlc_load.json").exists()


def test_refuses_foreign_files(setup):
    user, build = setup
    foreign = user / "mod" / "p00b_EXP-01A.mod"
    foreign.write_text('name="somebody else"\n', encoding="utf-8")
    with pytest.raises(KitError):
        inst.install("EXP-01A", user, build_root=build)
    with pytest.raises(KitError):
        inst.uninstall("EXP-01A", user, build_root=build)
    assert foreign.read_text(encoding="utf-8") == 'name="somebody else"\n'


