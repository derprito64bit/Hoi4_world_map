SUPPORTED_VERSION = "1.19.*"


def mod_name(build_id: str, title: str) -> str:
    return f"P00b {build_id} {title}"


def descriptor(build_id: str, title: str, replace_paths=(), path: str | None = None) -> str:
    """descriptor.mod / launcher .mod text (keys as in docs/logs/P00.md section 3 Launcher)."""
    lines = [f'name="{mod_name(build_id, title)}"', 'version="1"', f'supported_version="{SUPPORTED_VERSION}"',
             'tags={', '\t"Map"', '}']
    for rp in replace_paths:
        lines.append(f'replace_path="{rp}"')
    if path is not None:
        lines.append(f'path="{path}"')
    lines.append(f"# generated by {TOOL_TAG} (tools/experiments); do not edit")
    return "\n".join(lines) + "\n"


def _wrap(s: str, indent: str = "") -> str:
    """No hard wrapping: paths and commands must stay copy-pasteable (editors wrap long lines)."""
    return "\n".join(indent + para if para.strip() else "" for para in s.split("\n"))


def readme(build_id: str, title: str, *, prop: str, why: str, launch: str, steps: list, send: list,
           expected: str, cannot: list, user_dir: Path | None, notes: list = (),
           heading: str = "THE ONE THING THIS TEST CHANGES (compared with the normal game)") -> str:
    """One-page owner sheet. ``steps`` are the experiment-specific actions after the game has started."""
    ud = str(user_dir).replace("\\", "/") if user_dir else "$HOI4_USER_DIR"
    log = f"{ud}/logs/error.log"
    common_before = [
        "Close Hearts of Iron IV if it is running.",
        f"Open a terminal in the repository folder and run:\n      python tools/experiments/install.py {build_id}\n"
        f"   This writes one small file, {ud}/mod/p00b_{build_id}.mod, that points the launcher at this folder. "
        "It changes nothing else (not your playsets, not dlc_load.json).",
        f'Open the Paradox launcher -> Playsets -> make a new, empty playset (e.g. "P00b tests") -> Add mods -> '
        f'tick only "{mod_name(build_id, title)}". Untick every other mod.',
        f"Delete the old error log if it exists: {log} (the game writes a fresh one).",
        launch,
    ]
    common_after = [
        "Quit the game. Copy the error log NOW, before the next test overwrites it.",
        f"Uninstall when done:  python tools/experiments/install.py {build_id} --uninstall  "
        "(and remove the mod from the playset).",
    ]
    all_steps = common_before + list(steps) + common_after
    parts = [f"{build_id} — {title}", "=" * (len(build_id) + 3 + len(title)), ""]
    parts += [heading, _wrap(prop), ""]
    parts += ["WHY", _wrap(why), ""]
    parts += ["STEPS"]
    for i, s in enumerate(all_steps, 1):
        parts.append(_wrap(f"{i}. {s}"))
    parts += ["", "WHAT TO SEND BACK"]
    for s in list(send) + [f"The whole error log: {log} (say 'empty' if it has no lines)."]:
        parts.append(_wrap(f"- {s}"))
    notes = list(notes) + ["If the mod does not show up in the launcher after running install.py, report that "
                           "(the .mod file carries a '#' comment line the launcher is assumed to accept)."]
    if notes:
        parts += ["", "GOOD TO KNOW"]
        for s in notes:
            parts.append(_wrap(f"- {s}"))
    parts += ["", "EXPECTED OFFLINE VALIDATOR FINDING (checked by the kit before you got this)", _wrap(expected), ""]
    parts += ["WHAT THIS TEST CANNOT PROVE"]
    for c in cannot:
        parts.append(_wrap(f"- {c}: {CANNOT_PROVE[c]}"))
    return "\n".join(parts).rstrip() + "\n"


